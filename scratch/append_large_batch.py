# Limpando e pegando palavras únicas
words = set()
for line in raw_text.split('\n'):
    word = line.strip().lower()
    if word:
        words.add(word)

filepath = r'c:\Users\vitu\Documents\wordbomb\wordlists\Português.txt'

# Lendo palavras existentes para evitar duplicatas totais
try:
    with open(filepath, 'r', encoding='utf-8') as f:
        existing_words = {line.strip() for line in f}
except FileNotFoundError:
    existing_words = set()

# Filtrando as que já existem
new_words = sorted([w for w in words if w not in existing_words])

# Adicionando ao arquivo
with open(filepath, 'a', encoding='utf-8') as f:
    for word in new_words:
        f.write(f"\n{word}")

print(f"Added {len(new_words)} unique new words.")
